import { Guide, Label, Owner, Tier } from "./schema";

export const TIER_NAME: Record<Tier, string> = {
  open: "Open",
  capped: "Capped",
  reviewed: "Reviewed",
  gated: "Gated",
};

export const TIER_BLURB: Record<Tier, string> = {
  open: "Register and go. No provider review before external users can connect.",
  capped: "Anyone registers. Production use is capped until a light review lifts it.",
  reviewed: "A mandatory review with a real wait before external users can connect.",
  gated: "A partner program, business verification, paid assessment or legal entity stands between you and production.",
};

export const OWNER_NAME: Record<Owner, string> = {
  agent: "Agent does",
  agent_prepares: "Agent prepares, you submit",
  only_you: "Only you",
};

export const LABEL_NAME: Record<Label, string> = {
  tested: "Tested",
  documented: "Documented",
  reported: "Reported",
  unverified: "Unverified",
};

export function fmtDays(low: number | null, high: number | null): string {
  if (low == null || high == null) return "no published figure";
  if (low === high) return `${high} day${high === 1 ? "" : "s"}`;
  return `${low} to ${high} days`;
}

export function fmtHours(low: number, high: number): string {
  return `${low} to ${high} hours`;
}

export function guideToMarkdown(guide: Guide, baseUrl?: string): string {
  const L: string[] = [];
  const claimsById = new Map(guide.claims.map((c) => [c.id, c]));
  const sourcesById = new Map(guide.sources.map((s) => [s.id, s]));
  const cite = (ids: string[]) =>
    ids
      .map((id) => claimsById.get(id))
      .filter(Boolean)
      .map((c) => {
        const src = c!.sourceId ? sourcesById.get(c!.sourceId) : undefined;
        return src ? `[${LABEL_NAME[c!.label]}](${src.url})` : LABEL_NAME[c!.label];
      })
      .join(", ");

  L.push(`# ${guide.provider.name}: OAuth app setup guide`);
  L.push("");
  L.push(
    `${guide.reviewState === "reviewed" ? `Reviewed by ${guide.review?.reviewedBy} on ${guide.review?.reviewedOn}` : "Autogenerated, not yet reviewed"}. Verified on ${guide.verifiedOn}.${baseUrl ? ` Live version: ${baseUrl}/g/${guide.slug}` : ""}`,
  );
  L.push("");
  if (guide.noOAuth) {
    L.push(`**No OAuth for third party apps.** ${guide.noOAuth.reason}`);
    return L.join("\n");
  }

  L.push("## Step zero: do you need your own app?");
  L.push("");
  if (guide.managedAuth.managed === true) {
    L.push(`Composio manages an OAuth app for ${guide.provider.name} (${guide.managedAuth.schemes.join(", ")}; checked via ${guide.managedAuth.source} on ${guide.managedAuth.checkedAt.slice(0, 10)}). Use it unless you need:`);
  } else if (guide.managedAuth.managed === false) {
    L.push(`Composio has no managed OAuth app for ${guide.provider.name} (checked via ${guide.managedAuth.source} on ${guide.managedAuth.checkedAt.slice(0, 10)}), so you need your own. The reasons people build their own anyway:`);
  } else {
    L.push(`Could not confirm whether Composio manages an app for ${guide.provider.name}${guide.managedAuth.note ? ` (${guide.managedAuth.note})` : ""}. Check the toolkit page. Reasons to build your own regardless:`);
  }
  guide.managedAuth.customAppReasons.forEach((r) => L.push(`- ${r}`));
  L.push("");

  L.push("## Readiness");
  L.push("");
  L.push("| Scope class | Tier | What gates production | Calendar wait | Next action |");
  L.push("| --- | --- | --- | --- | --- |");
  guide.tiers.forEach((t, i) => {
    const sc = guide.scopeClasses.find((s) => s.id === t.scopeClassId);
    const w = guide.wait[i];
    const wait = `${fmtDays(w.lowDays, w.highDays)} (${LABEL_NAME[w.label]})${w.reported ? `, reported up to ${w.reported.highDays}` : ""}`;
    L.push(`| ${sc?.name ?? t.scopeClassId} | ${TIER_NAME[t.tier]}${t.flags.length ? ` (${t.flags.join(", ")})` : ""} | ${t.gate.replace(/\|/g, "/")} | ${wait} | ${guide.nextAction[t.scopeClassId].replace(/\|/g, "/")} |`);
  });
  L.push("");
  guide.tiers.forEach((t) => {
    const e = guide.effort[t.scopeClassId];
    if (!e) return;
    const sc = guide.scopeClasses.find((s) => s.id === t.scopeClassId);
    L.push(`Hands on effort${guide.tiers.length > 1 ? ` (${sc?.name ?? t.scopeClassId})` : ""}: ${fmtHours(e.lowHours, e.highHours)} (an estimate from: ${e.inputs.join("; ")}).`);
  });
  guide.tiers.forEach((t) => {
    const costs = guide.cost.filter((c) => !c.scopeClassId || c.scopeClassId === t.scopeClassId);
    if (!costs.length) return;
    const sc = guide.scopeClasses.find((s) => s.id === t.scopeClassId);
    L.push(`Costs${guide.tiers.length > 1 ? ` (${sc?.name ?? t.scopeClassId})` : ""}: ${costs.map((c) => c.text).join(" ")}`);
  });
  L.push("");

  if (guide.artifacts.length) {
    L.push("## Artifacts the provider demands");
    L.push("");
    guide.artifacts.forEach((a) => L.push(`- **${a.name}**: ${a.form} (${cite(a.claimIds)})`));
    L.push("");
  }

  L.push("## Steps");
  L.push("");
  guide.steps.forEach((s) => {
    L.push(`${s.n}. **${s.title}** [${OWNER_NAME[s.owner]}]${s.url ? ` ${s.url}` : ""}`);
    if (s.detail) L.push(`   ${s.detail}`);
    if (s.inputs.length) L.push(`   Inputs: ${s.inputs.join("; ")}`);
    if (s.claimIds.length) L.push(`   Evidence: ${cite(s.claimIds)}`);
  });
  L.push("");

  if (guide.playbooks.length) {
    L.push("## When you are blocked");
    L.push("");
    guide.playbooks.forEach((p) => {
      L.push(`- **${p.symptom}**`);
      L.push(`  Cause: ${p.cause}`);
      L.push(`  Fix: ${p.fix}${p.waitDays ? ` Expect about ${p.waitDays} days.` : ""} (${cite(p.claimIds)})`);
    });
    L.push("");
  }

  L.push("## Every claim and its evidence");
  L.push("");
  guide.claims.forEach((c) => {
    const src = c.sourceId ? sourcesById.get(c.sourceId) : undefined;
    const probe = c.probeId ? guide.probes.find((p) => p.id === c.probeId) : undefined;
    L.push(`- [${LABEL_NAME[c.label]}] ${c.text}${src ? ` ([${src.host}](${src.url}), retrieved ${src.retrievedAt.slice(0, 10)})` : ""}${probe ? ` (probe: ${probe.summary})` : ""}${c.quote ? `\n  > ${c.quote}` : ""}`);
  });
  L.push("");

  if (guide.gaps.length) {
    L.push("## Gaps");
    L.push("");
    guide.gaps.forEach((g) => L.push(`- ${g.what} (would be filled by ${g.page})`));
    L.push("");
  }

  L.push("## Verification note");
  L.push("");
  L.push("Tested:");
  (guide.verificationNote.tested.length ? guide.verificationNote.tested : ["Nothing beyond the probes listed above."]).forEach((t) => L.push(`- ${t}`));
  L.push("Corrected against sources:");
  (guide.verificationNote.corrected.length ? guide.verificationNote.corrected : ["Nothing recorded."]).forEach((t) => L.push(`- ${t}`));
  L.push("Still unverified:");
  (guide.verificationNote.unverified.length ? guide.verificationNote.unverified : ["Nothing recorded."]).forEach((t) => L.push(`- ${t}`));
  L.push("");

  L.push("## Sources");
  L.push("");
  guide.sources.forEach((s) => L.push(`- ${s.official ? "Official" : "Community"}: [${s.title ?? s.url}](${s.url}), ${s.status}, retrieved ${s.retrievedAt.slice(0, 10)}`));
  L.push("");
  return L.join("\n");
}
