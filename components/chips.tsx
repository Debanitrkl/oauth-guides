import { LABEL_NAME, OWNER_NAME, TIER_NAME } from "@/lib/markdown";
import { Flag, Label, Owner, Tier } from "@/lib/schema";

/* Meaning is carried by weight and line, not by a second hue. Flare is reserved for the survey line. */

const LABEL_CLASS: Record<Label, string> = {
  tested: "chip chip-solid",
  documented: "chip chip-line",
  reported: "chip chip-dashed",
  unverified: "chip chip-faint",
};

export function LabelChip({ label, host, title }: { label: Label; host?: string; title?: string }) {
  return (
    <span title={title ?? LABEL_NAME[label]} className={LABEL_CLASS[label]}>
      {LABEL_NAME[label]}
      {host ? <span className="normal-case tracking-normal opacity-70">{host}</span> : null}
    </span>
  );
}

const TIER_CLASS: Record<Tier, string> = {
  open: "chip chip-line",
  capped: "chip chip-line",
  reviewed: "chip chip-solid",
  gated: "chip chip-solid",
};

export function TierChip({ tier, large }: { tier: Tier; large?: boolean }) {
  return <span className={`${TIER_CLASS[tier]} ${large ? "px-3 py-1.5 text-[12px]" : ""}`}>{TIER_NAME[tier]}</span>;
}

const FLAG_TEXT: Record<Flag, string> = {
  paid: "Costs money",
  throttled: "Throttled until reviewed",
  permanent_choice: "A choice is permanent",
  entity_required: "Business entity required",
};

export function FlagChip({ flag }: { flag: Flag }) {
  return <span className="chip chip-faint normal-case tracking-normal">{FLAG_TEXT[flag]}</span>;
}

const OWNER_CLASS: Record<Owner, string> = {
  agent: "chip chip-line",
  agent_prepares: "chip chip-dashed",
  only_you: "chip chip-solid",
};

export function OwnerChip({ owner }: { owner: Owner }) {
  return <span className={OWNER_CLASS[owner]}>{OWNER_NAME[owner]}</span>;
}

export function ReviewChip({ state }: { state: "reviewed" | "autogenerated" }) {
  return state === "reviewed" ? <span className="chip chip-line">Reviewed by a person</span> : <span className="chip chip-dashed">Autogenerated, not reviewed</span>;
}
