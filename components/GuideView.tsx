"use client";

import { useMemo, useState } from "react";
import { fmtDays, fmtHours, LABEL_NAME, OWNER_NAME, TIER_BLURB, TIER_NAME } from "@/lib/markdown";
import { Claim, Guide } from "@/lib/schema";
import { FlagChip, LabelChip, OwnerChip, ReviewChip, TierChip } from "./chips";

export function GuideView({ guide, streaming }: { guide: Guide; streaming?: boolean }) {
  const [scopeId, setScopeId] = useState(guide.scopeClasses[0]?.id ?? guide.tiers[0]?.scopeClassId ?? "default");
  const idx = Math.max(0, guide.tiers.findIndex((t) => t.scopeClassId === scopeId));
  const tier = guide.tiers[idx];
  const wait = guide.wait[idx];
  const effort = tier ? guide.effort[tier.scopeClassId] ?? guide.effort.default : guide.effort.default;
  const claimsById = useMemo(() => new Map(guide.claims.map((c) => [c.id, c])), [guide.claims]);
  const sourcesById = useMemo(() => new Map(guide.sources.map((s) => [s.id, s])), [guide.sources]);
  const scope = guide.scopeClasses.find((s) => s.id === scopeId);
  const inScope = (ids?: string[]) => !ids || ids.length === 0 || ids.includes(scopeId);
  const steps = guide.steps.filter((s) => inScope(s.scopeClassIds));
  const artifacts = guide.artifacts.filter((a) => inScope(a.scopeClassIds));
  const costs = guide.cost.filter((c) => !c.scopeClassId || c.scopeClassId === scopeId);
  const [copied, setCopied] = useState(false);

  const cardText = () => {
    if (!tier) return "";
    const lines = [
      `${guide.provider.name} OAuth app readiness${scope ? ` (${scope.name})` : ""}`,
      `Tier: ${TIER_NAME[tier.tier]}. ${tier.gate}`,
      `Calendar wait: ${fmtDays(wait.lowDays, wait.highDays)} (${LABEL_NAME[wait.label]})${wait.reported ? `; developers report up to ${wait.reported.highDays} days` : ""}`,
      `Hands on effort: ${effort ? fmtHours(effort.lowHours, effort.highHours) : "not estimated"} (estimate)`,
      `Artifacts to prepare: ${artifacts.length}${artifacts.length ? ": " + artifacts.map((a) => a.name).join(", ") : ""}`,
      costs.length ? `Costs: ${costs.map((c) => c.text).join(" ")}` : "",
      `Next action: ${guide.nextAction[tier.scopeClassId]}`,
      `Verified on ${guide.verifiedOn.slice(0, 10)}, ${guide.reviewState === "reviewed" ? "reviewed" : "autogenerated"}. ${typeof window !== "undefined" ? window.location.origin : ""}/g/${guide.slug}`,
    ].filter(Boolean);
    return lines.join("\n");
  };

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(cardText());
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      // clipboard unavailable
    }
  };

  const evidence = (ids: string[]) => (
    <span className="inline-flex flex-wrap gap-1.5 align-middle">
      {ids
        .map((id) => claimsById.get(id))
        .filter((c): c is Claim => !!c)
        .map((c) => {
          const src = c.sourceId ? sourcesById.get(c.sourceId) : undefined;
          return (
            <a key={c.id} href={`#claim-${c.id}`} className="no-underline" title={c.text}>
              <LabelChip label={c.label} host={src?.host} />
            </a>
          );
        })}
    </span>
  );

  if (guide.noOAuth) {
    return (
      <article className="space-y-8">
        <Header guide={guide} />
        <section className="plate p-6">
          <h2 className="t-title text-chalk">No OAuth app to set up</h2>
          <p className="mt-3 max-w-prose text-chalk-mid">{guide.noOAuth.reason}</p>
          <p className="mt-3 max-w-prose text-sm text-chalk-faint">This verdict comes from the resolve step. If you believe it is wrong, generate again with the provider&apos;s developer portal URL as the query.</p>
        </section>
        <VerificationNote guide={guide} />
      </article>
    );
  }

  return (
    <article className="space-y-12">
      <Header guide={guide} streaming={streaming} />

      <section className="plate p-6">
        <h2 className="t-title text-chalk">Do you need your own app?</h2>
        {guide.managedAuth.managed === true ? (
          <p className="mt-3 max-w-prose text-chalk-mid">
            Composio manages an OAuth app for {guide.provider.name} ({guide.managedAuth.schemes.join(", ") || "OAuth"}). Start with managed auth and build your own only if you need one of these:
          </p>
        ) : guide.managedAuth.managed === false ? (
          <p className="mt-3 max-w-prose text-chalk-mid">Composio has no managed OAuth app for {guide.provider.name}, so you need your own. The usual reasons people build their own even when a managed app exists:</p>
        ) : (
          <p className="mt-3 max-w-prose text-chalk-mid">
            We could not confirm whether Composio manages an app for {guide.provider.name}
            {guide.managedAuth.note ? ` (${guide.managedAuth.note})` : ""}. Check the toolkit page. Reasons to build your own regardless:
          </p>
        )}
        <ul className="mt-4 grid gap-x-8 gap-y-1.5 text-sm text-chalk sm:grid-cols-2">
          {guide.managedAuth.customAppReasons.map((r) => (
            <li key={r} className="border-t border-hairline pt-1.5">
              {r}
            </li>
          ))}
        </ul>
        <p className="t-mono mt-4 text-chalk-faint">
          Checked via {guide.managedAuth.source === "api" ? "Composio's toolkit API" : guide.managedAuth.source === "cache" ? "the bundled list" : "nothing"} on {guide.managedAuth.checkedAt.slice(0, 10)}
        </p>
      </section>

      {guide.scopeClasses.length > 1 && (
        <section>
          <h2 className="t-title text-chalk">Which scopes do you need?</h2>
          <p className="mt-2 text-sm text-chalk-mid">The tier, the wait and the steps change with the answer.</p>
          <div className="mt-4 flex flex-wrap gap-2" role="group" aria-label="Scope class">
            {guide.scopeClasses.map((s) => {
              const t = guide.tiers.find((x) => x.scopeClassId === s.id);
              const active = s.id === scopeId;
              return (
                <button
                  key={s.id}
                  type="button"
                  onClick={() => setScopeId(s.id)}
                  aria-pressed={active}
                  className={`rounded-[14px] px-4 py-3 text-left transition-colors ${active ? "bg-chalk text-basalt" : "plate text-chalk hover:bg-basalt-3"}`}
                >
                  <div className="flex items-center gap-3">
                    <span className="text-[15px] font-medium">{s.name}</span>
                    {t && <span className={`t-mono ${active ? "text-basalt/70" : "text-chalk-faint"}`}>{TIER_NAME[t.tier]}</span>}
                  </div>
                  {s.examples.length > 0 && <div className={`t-mono mt-1 ${active ? "text-basalt/60" : "text-chalk-faint"}`}>{s.examples.slice(0, 4).join("  ")}</div>}
                </button>
              );
            })}
          </div>
          {scope?.description && <p className="mt-3 max-w-prose text-sm text-chalk-mid">{scope.description}</p>}
        </section>
      )}

      {tier && (
        <section className="plate-raised survey overflow-hidden p-6" key={tier.scopeClassId}>
          <div className="flex flex-wrap items-start justify-between gap-4">
            <div>
              <h2 className="t-title text-chalk">Readiness{scope && guide.scopeClasses.length > 1 ? `: ${scope.name}` : ""}</h2>
              <div className="mt-3 flex flex-wrap items-center gap-2">
                <TierChip tier={tier.tier} large />
                {tier.flags.map((f) => (
                  <FlagChip key={f} flag={f} />
                ))}
              </div>
              <p className="mt-3 max-w-prose text-sm text-chalk-mid">{TIER_BLURB[tier.tier]}</p>
            </div>
            <button type="button" onClick={copy} className="pill pill-ghost pill-sm">
              {copied ? "Copied" : "Copy card as text"}
            </button>
          </div>

          <dl className="mt-7 grid gap-6 border-t border-hairline pt-6 sm:grid-cols-2 lg:grid-cols-4">
            <div>
              <dt className="t-label">What gates production</dt>
              <dd className="mt-2 text-sm text-chalk">
                {tier.gate} <span className="mt-1.5 block">{evidence(tier.claimIds)}</span>
              </dd>
            </div>
            <div>
              <dt className="t-label">Calendar wait</dt>
              <dd className="mt-2">
                <div className="flex flex-wrap items-baseline gap-2">
                  <span className="t-stat text-chalk">{fmtDays(wait.lowDays, wait.highDays)}</span>
                  <LabelChip label={wait.label} />
                </div>
                {wait.reported && (
                  <div className="mt-2 text-sm text-chalk">
                    Developers report {wait.reported.lowDays} to {wait.reported.highDays} days <LabelChip label="reported" />
                  </div>
                )}
                {wait.note && <div className="mt-1.5 text-sm text-chalk-mid">{wait.note}</div>}
                <div className="mt-2">{evidence(wait.claimIds)}</div>
              </dd>
            </div>
            <div>
              <dt className="t-label">Hands on effort</dt>
              <dd className="mt-2">
                <span className="t-stat text-chalk">{effort ? fmtHours(effort.lowHours, effort.highHours) : "not estimated"}</span>
                <details className="mt-2 text-sm text-chalk-mid">
                  <summary className="cursor-pointer">An estimate by rule, from</summary>
                  <ul className="mt-1.5 space-y-1 border-l border-hairline-strong pl-3">
                    {(effort?.inputs ?? []).map((i) => (
                      <li key={i}>{i}</li>
                    ))}
                  </ul>
                </details>
              </dd>
            </div>
            <div>
              <dt className="t-label">Artifacts and costs</dt>
              <dd className="mt-2">
                <span className="t-stat text-chalk">{artifacts.length}</span> <span className="text-sm text-chalk-mid">artifact{artifacts.length === 1 ? "" : "s"} to prepare</span>
                {costs.length > 0 && (
                  <ul className="mt-2 space-y-1.5 text-sm text-chalk">
                    {costs.map((c) => (
                      <li key={c.text}>
                        {c.text} {evidence(c.claimIds)}
                      </li>
                    ))}
                  </ul>
                )}
              </dd>
            </div>
          </dl>

          <div className="mt-7 border-t border-hairline-strong pt-5">
            <div className="t-label text-flare-soft">Next action</div>
            <p className="mt-2 max-w-4xl text-[17px] leading-snug text-chalk">{guide.nextAction[tier.scopeClassId]}</p>
          </div>
        </section>
      )}

      {artifacts.length > 0 && (
        <section>
          <h2 className="t-title text-chalk">Artifacts the provider demands</h2>
          <p className="mt-2 max-w-prose text-sm text-chalk-mid">Share this list with whoever produces them. The agent drafts the written ones; the form column says what the provider accepts.</p>
          <table className="mt-5 w-full text-sm">
            <thead>
              <tr className="border-b border-hairline-strong text-left">
                <th className="t-label py-2 pr-4 font-normal">Artifact</th>
                <th className="t-label py-2 pr-4 font-normal">Form</th>
                <th className="t-label py-2 font-normal">Evidence</th>
              </tr>
            </thead>
            <tbody className="align-top">
              {artifacts.map((a) => (
                <tr key={a.name} className="border-b border-hairline">
                  <td className="py-3 pr-4 font-medium text-chalk">{a.name}</td>
                  <td className="py-3 pr-4 text-chalk-mid">{a.form}</td>
                  <td className="py-3">{evidence(a.claimIds)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      )}

      <section>
        <h2 className="t-title text-chalk">Steps</h2>
        <p className="mt-2 max-w-prose text-sm text-chalk-mid">
          Each step names who can do it. {OWNER_NAME.agent}: an agent can perform or draft it. {OWNER_NAME.agent_prepares}: the agent fills the form, you press submit. {OWNER_NAME.only_you}: your account, your signature, your money or your identity.
        </p>
        {steps.length === 0 ? (
          <p className="mt-4 text-sm text-chalk-mid">No steps were extracted. See the gaps below.</p>
        ) : (
          <ol className="ledger mt-5 border-t border-hairline-strong">
            {steps.map((s, i) => (
              <li key={`${s.n}-${s.title}`} className="grid grid-cols-[2.5rem_1fr] gap-x-3 py-5">
                <span className="t-mono pt-1 text-chalk-faint">{String(i + 1).padStart(2, "0")}</span>
                <div>
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="text-[16px] font-medium text-chalk">{s.title}</span>
                    <OwnerChip owner={s.owner} />
                    {s.attemptId && <LabelChip label="tested" title="From a recorded walkthrough" />}
                  </div>
                  {s.detail && <p className="mt-1.5 max-w-prose text-sm text-chalk-mid">{s.detail}</p>}
                  {s.inputs.length > 0 && (
                    <p className="mt-1.5 max-w-prose text-sm text-chalk-mid">
                      <span className="t-label mr-2">Have ready</span>
                      {s.inputs.join("; ")}
                    </p>
                  )}
                  <div className="mt-2 flex flex-wrap items-center gap-2">
                    {s.url && (
                      <a href={s.url} target="_blank" rel="noreferrer" className="t-mono text-flare-soft">
                        {hostLabel(s.url)}
                      </a>
                    )}
                    {evidence(s.claimIds)}
                  </div>
                </div>
              </li>
            ))}
          </ol>
        )}
      </section>

      {guide.attempts && guide.attempts.length > 0 && (
        <section>
          <h2 className="t-title text-chalk">Recorded walkthroughs</h2>
          <p className="mt-2 max-w-prose text-sm text-chalk-mid">Screens a person walked with a real account, recorded field by field. They back the Tested steps above.</p>
          {guide.attempts.map((a) => (
            <details key={a.id} className="plate mt-4 p-5">
              <summary className="cursor-pointer font-medium text-chalk">
                {a.title} <span className="t-mono ml-2 text-chalk-faint">{a.account}, {a.recordedOn}</span>
              </summary>
              <ol className="mt-3 space-y-2 text-sm">
                {a.screens.map((sc) => (
                  <li key={sc.n} className="grid grid-cols-[2rem_1fr] gap-x-2">
                    <span className="t-mono text-chalk-faint">{sc.n}</span>
                    <div>
                      <span className="font-medium text-chalk">{sc.title}</span>
                      {sc.fields.length > 0 && <span className="text-chalk-mid"> · fields: {sc.fields.join(", ")}</span>}
                      {sc.note && <div className="text-chalk-mid">{sc.note}</div>}
                      {sc.stoppedAt && <div className="t-mono mt-1 text-flare-soft">Stopped here: the next action is only yours</div>}
                    </div>
                  </li>
                ))}
              </ol>
            </details>
          ))}
        </section>
      )}

      {guide.playbooks.length > 0 && (
        <section>
          <h2 className="t-title text-chalk">When you are blocked</h2>
          <div className="mt-5 grid gap-px overflow-hidden rounded-[20px] bg-hairline md:grid-cols-2">
            {guide.playbooks.map((p) => (
              <div key={p.symptom} className="bg-basalt-2 p-5 text-sm">
                <div className="text-[16px] font-medium leading-snug text-chalk">{p.symptom}</div>
                <dl className="mt-3 space-y-2">
                  <div className="grid grid-cols-[3.2rem_1fr] gap-x-2">
                    <dt className="t-label pt-1">Cause</dt>
                    <dd className="text-chalk-mid">{p.cause}</dd>
                  </div>
                  <div className="grid grid-cols-[3.2rem_1fr] gap-x-2">
                    <dt className="t-label pt-1">Fix</dt>
                    <dd className="text-chalk">
                      {p.fix}
                      {p.waitDays ? ` Expect about ${p.waitDays} days.` : ""}
                    </dd>
                  </div>
                </dl>
                <div className="mt-3">{evidence(p.claimIds)}</div>
              </div>
            ))}
          </div>
        </section>
      )}

      <section>
        <h2 className="t-title text-chalk">Every claim and its evidence</h2>
        <p className="mt-2 max-w-prose text-sm text-chalk-mid">
          {guide.stats.claims} claims: {guide.stats.byLabel.tested ?? 0} tested, {guide.stats.byLabel.documented ?? 0} documented, {guide.stats.byLabel.reported ?? 0} reported, {guide.stats.byLabel.unverified ?? 0} unverified. Open a claim to see the exact words it rests on.
        </p>
        <ul className="ledger mt-5 border-t border-hairline-strong">
          {guide.claims.map((c) => {
            const src = c.sourceId ? sourcesById.get(c.sourceId) : undefined;
            const probe = c.probeId ? guide.probes.find((p) => p.id === c.probeId) : undefined;
            return (
              <li key={c.id} id={`claim-${c.id}`} className="scroll-mt-20 py-3 text-sm">
                <div className="flex flex-wrap items-start gap-2.5">
                  <LabelChip label={c.label} host={src?.host} />
                  <span className="flex-1 text-chalk">{c.text}</span>
                </div>
                {(c.quote || probe || c.reviewerNote) && (
                  <details className="mt-1.5 pl-1 text-chalk-mid">
                    <summary className="t-mono cursor-pointer text-chalk-faint">Evidence</summary>
                    {c.quote && (
                      <blockquote className="mt-2 max-w-prose border-l border-hairline-strong pl-3 italic">
                        &ldquo;{c.quote}&rdquo;
                        {src && (
                          <span className="not-italic">
                            {" "}
                            from{" "}
                            <a href={src.url} target="_blank" rel="noreferrer" className="text-flare-soft">
                              {src.title ?? src.url}
                            </a>
                            , retrieved {src.retrievedAt.slice(0, 10)}
                          </span>
                        )}
                      </blockquote>
                    )}
                    {probe && (
                      <div className="mt-2 max-w-prose">
                        Probe: {probe.summary} <span className="t-mono text-chalk-faint">({probe.kind}, {probe.ranAt.slice(0, 10)})</span>
                      </div>
                    )}
                    {c.reviewerNote && <div className="mt-2 max-w-prose">Reviewer: {c.reviewerNote}</div>}
                  </details>
                )}
              </li>
            );
          })}
        </ul>
      </section>

      {guide.gaps.length > 0 && (
        <section>
          <h2 className="t-title text-chalk">Gaps</h2>
          <ul className="ledger mt-4 border-t border-hairline-strong text-sm">
            {guide.gaps.map((g) => (
              <li key={g.what + g.page} className="py-3 text-chalk-mid">
                {g.what}. Would be filled by{" "}
                <a href={g.page} target="_blank" rel="noreferrer" className="text-flare-soft">
                  {hostLabel(g.page)}
                </a>
                .
              </li>
            ))}
          </ul>
        </section>
      )}

      <VerificationNote guide={guide} />

      <section>
        <h2 className="t-title text-chalk">Probes and sources</h2>
        {guide.probes.length > 0 && (
          <ul className="ledger mt-4 border-t border-hairline-strong text-sm">
            {guide.probes.map((p) => (
              <li key={p.id} className="grid grid-cols-[9rem_1fr] gap-x-3 py-2.5">
                <span className={`t-mono ${p.ok ? "text-chalk" : "text-chalk-faint"}`}>{p.kind}</span>
                <span className="text-chalk-mid">{p.summary}</span>
              </li>
            ))}
          </ul>
        )}
        <ul className="ledger mt-6 border-t border-hairline-strong text-sm">
          {guide.sources.map((s) => (
            <li key={s.id} className="grid grid-cols-[6rem_1fr] gap-x-3 py-2.5">
              <span className="t-mono text-chalk-faint">{s.official ? "official" : "community"}</span>
              <span>
                <a href={s.url} target="_blank" rel="noreferrer" className="text-chalk hover:text-flare-soft">
                  {s.title ?? s.url}
                </a>
                <span className="t-mono ml-2 text-chalk-faint">
                  {s.status} · {s.retrievedAt.slice(0, 10)}
                  {s.chars ? ` · ${s.chars.toLocaleString()} chars` : ""}
                </span>
              </span>
            </li>
          ))}
        </ul>
      </section>
    </article>
  );
}

function Header({ guide, streaming }: { guide: Guide; streaming?: boolean }) {
  return (
    <header className="rise flex flex-wrap items-end justify-between gap-5 border-b border-hairline-strong pb-6">
      <div>
        <h1 className="t-headline text-chalk">{guide.provider.name}</h1>
        <div className="t-mono mt-3 flex flex-wrap items-center gap-x-3 gap-y-1.5 text-chalk-faint">
          {guide.provider.domain && <span>{guide.provider.domain}</span>}
          {guide.provider.oauthProducts.length > 0 && <span>{guide.provider.oauthProducts.join(" · ")}</span>}
          <ReviewChip state={guide.reviewState} />
          <span>verified {guide.verifiedOn.slice(0, 10)}</span>
          {guide.review && <span>reviewed by {guide.review.reviewedBy}</span>}
        </div>
        {guide.provider.variantNote && <p className="mt-3 max-w-prose text-sm text-chalk-mid">{guide.provider.variantNote}</p>}
      </div>
      {!streaming && (
        <div className="flex flex-wrap gap-2">
          {guide.provider.portalUrl && (
            <a href={guide.provider.portalUrl} target="_blank" rel="noreferrer" className="pill pill-ghost pill-sm arrow no-underline">
              Developer portal
            </a>
          )}
          <a href={`/g/${guide.slug}/markdown`} className="pill pill-ghost pill-sm no-underline">
            Export markdown
          </a>
        </div>
      )}
    </header>
  );
}

function VerificationNote({ guide }: { guide: Guide }) {
  const v = guide.verificationNote;
  const col = (title: string, items: string[], empty: string) => (
    <div>
      <div className="t-label">{title}</div>
      <ul className="mt-3 space-y-2 text-sm text-chalk-mid">
        {(items.length ? items : [empty]).map((t) => (
          <li key={t} className="border-t border-hairline pt-2">
            {t}
          </li>
        ))}
      </ul>
    </div>
  );
  return (
    <section className="plate p-6">
      <h2 className="t-title text-chalk">Verification note</h2>
      <div className="mt-5 grid gap-6 md:grid-cols-3">
        {col("Tested", v.tested, "Nothing beyond the probes listed below.")}
        {col("Corrected against sources", v.corrected, "Nothing recorded.")}
        {col("Still unverified", v.unverified, "Nothing recorded.")}
      </div>
      {guide.review?.corrections.length ? (
        <div className="mt-6">
          <div className="t-label">Reviewer corrections</div>
          <ul className="mt-3 space-y-2 text-sm text-chalk-mid">
            {guide.review.corrections.map((c) => (
              <li key={c} className="border-t border-hairline pt-2">
                {c}
              </li>
            ))}
          </ul>
        </div>
      ) : null}
    </section>
  );
}

function hostLabel(url: string): string {
  try {
    const u = new URL(url);
    return u.hostname + (u.pathname.length > 1 ? u.pathname.replace(/\/$/, "") : "");
  } catch {
    return url;
  }
}
